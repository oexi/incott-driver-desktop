export function keycodeToHid(code) {
  for (const k of vkPOS) if (k[0] === code) return k[2];
  return 0;
}
export function keynameToHid(name) {
  for (const k of vkPOS) if (k[1] === name) return k[2];
  return 0;
}
export function hidToKeyname(hid) {
  for (const k of vkPOS) if (k[2] === hid) return k[1];
  return "";
}
export function keycodeToKeyname(code) {
  for (const k of vkPOS) if (k[0] === code) return k[1];
  return "";
}
